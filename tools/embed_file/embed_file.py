"""Writes a C++ source file holding a file's bytes, so a program carries the
file inside it (fonts, for instance) rather than finding it when it runs.

Usage: embed_file.py INPUT OUTPUT NAMESPACE SYMBOL

OUTPUT defines `const unsigned char SYMBOL[]` and `const std::size_t
SYMBOLSize` in NAMESPACE. Declare them in a header of your own (see
embed_file.bzl).
"""

import pathlib
import sys


def main(argv):
    if len(argv) != 4:
        sys.exit(__doc__)
    source, output, namespace, symbol = argv
    data = pathlib.Path(source).read_bytes()
    rows = (", ".join(str(byte) for byte in data[i:i + 24]) for i in range(0, len(data), 24))
    pathlib.Path(output).write_text(
        f"// Generated by tools/embed_file from {pathlib.Path(source).name}: don't edit.\n"
        "#include <cstddef>\n\n"
        f"namespace {namespace} {{\n"
        f"extern const unsigned char {symbol}[] = {{\n" + ",\n".join(rows) + "};\n"
        f"extern const std::size_t {symbol}Size = {len(data)};\n"
        f"}} // namespace {namespace}\n")


if __name__ == "__main__":
    main(sys.argv[1:])
