// The cook tool (see README.md), run by //tools/assets' rules:
//
//   cook model --gltf ship.glb --name ship --object Ship --label //a:ship
//       --report ship.report.json --counts ship.counts
//       --output PLATFORM NAMESPACE CC H POLYGONS VERTICES MODE ...
//
// writes each platform's version of the model as C++ (a Scene::MeshData
// named `name` in NAMESPACE), simplified to its budget (POLYGONS, VERTICES;
// 0 is no limit) if MODE allows, and fails if it doesn't fit. And
//
//   cook scene --label //a:hangar --report hangar.report.txt
//       --limit PLATFORM POLYGONS VERTICES ... --model COUNTS HOW_MANY ...
//
// adds up what a scene's models cost each platform (each times how many are
// shown at once) and fails if a platform's total is over its limit.
#include "Cook.hpp"
#include "Gltf.hpp"

#include <algorithm>
#include <cctype>
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <map>
#include <sstream>
#include <string>
#include <vector>

namespace {

struct Output {
  std::string platform, nameSpace, cc, h;
  Cook::Budget budget;
  Cook::Mode mode;
};

int usage(const char *problem) {
  std::fprintf(stderr, "cook: %s (see tools/assets/cook/main.cpp)\n", problem);
  return 2;
}

// The platform's name in capitals, as an object made for it is named
// (Ship_DS, Ship_3DS)
std::string upperCase(std::string platform) {
  for (char &c : platform)
    c = static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
  return platform;
}

// How the platform's name reads in a message
std::string displayName(const std::string &platform) {
  return platform == "ds" ? "the DS" : platform == "3ds" ? "the 3DS" : platform;
}

// How the platform draws a model, which its budget counts: quads and
// strips on the DS, separate triangles elsewhere
Cook::Drawing drawingOn(const std::string &platform) {
  return platform == "ds" ? Cook::Drawing::quadsAndStrips : Cook::Drawing::triangles;
}

std::string percentOver(std::uint32_t cost, std::uint32_t budget) {
  char text[32];
  std::snprintf(text, sizeof text, "%.0f%%", 100.0 * (cost - budget) / budget);
  return text;
}

// `value` as a C++ float literal that reads back exactly: 0 is "0.0f", not
// "0f" (which isn't one)
std::string floatLiteral(float value) {
  char text[32];
  std::snprintf(text, sizeof text, "%.9g", value);
  std::string literal = text;
  if (literal.find_first_of(".en") == std::string::npos)
    literal += ".0";
  return literal + "f";
}

// The model as C++: a Scene::MeshData named `name` in `nameSpace`, and how
// many triangles, vertices and polygons (as the platform draws it) it has,
// as constants. For the DS, its indices are its quads, strips and
// triangles, which MeshData's primitives give.
void writeCpp(const Cook::Mesh &mesh, const std::string &name, const Output &output,
              const std::string &source, bool doubleSided) {
  const Cook::Drawing drawing = drawingOn(output.platform);
  ScratchPadd::Scene::Primitives primitives;
  if (drawing == Cook::Drawing::quadsAndStrips)
    primitives = Cook::primitivesOf(mesh);
  else
    primitives.indices = mesh.indices;
  std::ofstream h(output.h);
  h << "// Generated by //tools/assets:cook from " << source << " (" << output.platform
    << "). Don't edit.\n#pragma once\n\n#include <ScratchPadd/Scene/MeshData.hpp>\n\n#include "
       "<cstdint>\n\nnamespace "
    << output.nameSpace << " {\nextern const ScratchPadd::Scene::MeshData " << name
    << ";\ninline constexpr std::uint32_t " << name << "Triangles = " << mesh.triangleCount()
    << ";\ninline constexpr std::uint32_t " << name << "Vertices = " << mesh.vertexCount()
    << ";\ninline constexpr std::uint32_t " << name
    << "Polygons = " << Cook::costOf(mesh, drawing).polygons << ";\n} // namespace "
    << output.nameSpace << "\n";

  std::ofstream cc(output.cc);
  const std::string header = output.h.substr(output.h.find_last_of('/') + 1);
  cc << "// Generated by //tools/assets:cook from " << source << " (" << output.platform
     << "). Don't edit.\n#include \"" << header << "\"\n\nnamespace " << output.nameSpace
     << " {\nnamespace {\n// constexpr: the numbers are converted when compiling, also where "
        "Scalar is\n"
        "// fixed point (the DS, which has no floating-point hardware)\n"
        "constexpr ScratchPadd::Scene::Vertex kVertices[] = {\n";
  for (const ScratchPadd::Scene::Vertex &v : Cook::sceneVertices(mesh)) {
    const auto &p = v.position, &n = v.normal;
    const ScratchPadd::Scene::Colour &c = v.colour;
    cc << "    {{" << floatLiteral(p.x) << ", " << floatLiteral(p.y) << ", " << floatLiteral(p.z)
       << "}, {" << floatLiteral(n.x) << ", " << floatLiteral(n.y) << ", " << floatLiteral(n.z)
       << "}, {" << int(c.r) << ", " << int(c.g) << ", " << int(c.b) << ", " << int(c.a) << "}},\n";
  }
  cc << "};\nconstexpr std::uint32_t kIndices[] = {";
  for (std::size_t i = 0; i < primitives.indices.size(); ++i)
    cc << (i % 16 == 0 ? "\n    " : " ") << primitives.indices[i] << ",";
  cc << "\n};\n";
  std::string meshArrays = "kVertices, kIndices";
  if (!primitives.runs.empty()) {
    static constexpr const char *kKinds[] = {"triangles", "quads", "triangleStrip"};
    cc << "// The indices' runs: how the DS draws them\n"
          "using Kind = ScratchPadd::Scene::Primitive::Kind;\n"
          "constexpr ScratchPadd::Scene::Primitive kPrimitives[] = {\n";
    for (const ScratchPadd::Scene::Primitive &run : primitives.runs)
      cc << "    {Kind::" << kKinds[static_cast<int>(run.kind)] << ", "
         << static_cast<int>(run.alpha) << ", " << run.indexCount << "},\n";
    cc << "};\n";
    meshArrays += ", kPrimitives";
  } else {
    meshArrays += ", {}";
  }
  meshArrays += doubleSided ? ", true" : ", false";
  cc << "} // namespace\n\nconst ScratchPadd::Scene::MeshData " << name << "{" << meshArrays
     << "};\n} // namespace " << output.nameSpace << "\n";
}

int cookModel(int argc, char **argv) {
  std::string gltf, name, object, label, reportPath, countsPath;
  std::vector<Output> outputs;
  for (int i = 2; i < argc; ++i) {
    const std::string arg = argv[i];
    auto next = [&]() -> std::string { return i + 1 < argc ? argv[++i] : ""; };
    if (arg == "--gltf")
      gltf = next();
    else if (arg == "--name")
      name = next();
    else if (arg == "--object")
      object = next();
    else if (arg == "--label")
      label = next();
    else if (arg == "--report")
      reportPath = next();
    else if (arg == "--counts")
      countsPath = next();
    else if (arg == "--output") {
      Output output;
      output.platform = next();
      output.nameSpace = next();
      output.cc = next();
      output.h = next();
      output.budget.polygons = static_cast<std::uint32_t>(std::stoul(next()));
      output.budget.vertices = static_cast<std::uint32_t>(std::stoul(next()));
      const auto mode = Cook::modeFromName(next());
      if (!mode)
        return usage("a mode is FAIL, SIMPLIFY or SIMPLIFY_AGGRESSIVE");
      output.mode = *mode;
      outputs.push_back(output);
    } else
      return usage(("unknown argument " + arg).c_str());
  }
  if (gltf.empty() || name.empty() || object.empty() || outputs.empty())
    return usage("cook model needs --gltf, --name, --object and an --output");

  std::ostringstream report, counts;
  report << "{\n  \"model\": \"" << label << "\",\n  \"object\": \"" << object
         << "\",\n  \"platforms\": {";
  bool failed = false;
  for (std::size_t o = 0; o < outputs.size(); ++o) {
    const Output &output = outputs[o];
    std::string error;
    const auto model = Cook::readModel(gltf, object, output.platform, error);
    if (!model) {
      std::fprintf(stderr, "%s: %s\n", label.c_str(), error.c_str());
      return 1;
    }
    const Cook::Drawing drawing = drawingOn(output.platform);
    // Culled if it's closed (its shape as made, before any simplifying), or
    // if Blender's Backface Culling is ticked; double-sided if it's open
    const Cook::Sides sides = Cook::sidesOf(model->mesh);
    const bool doubleSided = !sides.closed && !model->backfaceCulling;
    const Cook::Cooked cooked = Cook::cook(model->mesh, output.budget, output.mode, drawing);
    const Cook::Budget before = Cook::costOf(model->mesh, drawing),
                       after = Cook::costOf(cooked.mesh, drawing);
    report << (o ? "," : "") << "\n    \"" << output.platform << "\": {\"object\": \""
           << model->object << "\", \"mode\": \"" << Cook::nameOf(output.mode)
           << "\", \"budget\": {\"polygons\": " << output.budget.polygons
           << ", \"vertices\": " << output.budget.vertices
           << "}, \"before\": {\"polygons\": " << before.polygons
           << ", \"vertices\": " << before.vertices
           << "}, \"after\": {\"polygons\": " << after.polygons
           << ", \"vertices\": " << after.vertices
           << "}, \"sides\": {\"closed\": " << (sides.closed ? "true" : "false")
           << ", \"openEdges\": " << sides.openEdges
           << ", \"backfaceCulling\": " << (model->backfaceCulling ? "true" : "false")
           << ", \"doubleSided\": " << (doubleSided ? "true" : "false")
           << "}, \"error\": " << cooked.error << ", \"steps\": [";
    for (std::size_t s = 0; s < cooked.steps.size(); ++s)
      report << (s ? ", " : "") << '"' << cooked.steps[s] << '"';
    report << "], \"fits\": " << (cooked.fitsBudget ? "true" : "false") << "}";
    counts << output.platform << " " << after.polygons << " " << after.vertices << "\n";

    if (!cooked.fitsBudget) {
      failed = true;
      const Cook::Budget &budget = output.budget;
      std::fprintf(stderr,
                   "%s: %s (object %s) is over %s's budget: %u polygons and %u vertices, against "
                   "%u and %u (%s over).\n",
                   label.c_str(), name.c_str(), model->object.c_str(),
                   displayName(output.platform).c_str(), after.polygons, after.vertices,
                   budget.polygons, budget.vertices,
                   percentOver(after.polygons, budget.polygons).c_str());
      if (output.mode == Cook::Mode::fail) {
        std::fprintf(
            stderr,
            "  To fit it: over_budget = {\"%s\": \"SIMPLIFY\"} (or \"SIMPLIFY_AGGRESSIVE\"), "
            "an object made for it named %s_%s in the .blend, or a bigger budget.\n",
            output.platform.c_str(), object.c_str(), upperCase(output.platform).c_str());
      } else {
        std::fprintf(stderr, "  %s got it to that (%s, error %.3f of its size)%s.\n",
                     Cook::nameOf(output.mode), cooked.steps.back().c_str(), cooked.error,
                     output.mode == Cook::Mode::simplify
                         ? ", keeping its look; SIMPLIFY_AGGRESSIVE goes further"
                         : "");
      }
      continue;
    }
    writeCpp(cooked.mesh, name, output, label + " (object " + model->object + ")", doubleSided);
  }
  report << "\n  }\n}\n";
  if (!reportPath.empty())
    std::ofstream(reportPath) << report.str();
  if (!countsPath.empty())
    std::ofstream(countsPath) << counts.str();
  return failed ? 1 : 0;
}

int checkScene(int argc, char **argv) {
  std::string label, reportPath;
  std::map<std::string, Cook::Budget> limits;
  struct Model {
    std::string counts;
    std::uint32_t howMany;
  };
  std::vector<Model> models;
  for (int i = 2; i < argc; ++i) {
    const std::string arg = argv[i];
    auto next = [&]() -> std::string { return i + 1 < argc ? argv[++i] : ""; };
    if (arg == "--label")
      label = next();
    else if (arg == "--report")
      reportPath = next();
    else if (arg == "--limit") {
      const std::string platform = next();
      limits[platform].polygons = static_cast<std::uint32_t>(std::stoul(next()));
      limits[platform].vertices = static_cast<std::uint32_t>(std::stoul(next()));
    } else if (arg == "--model") {
      const std::string counts = next();
      models.push_back({counts, static_cast<std::uint32_t>(std::stoul(next()))});
    } else
      return usage(("unknown argument " + arg).c_str());
  }

  // Each platform's total, and each model's part of it
  std::map<std::string, Cook::Budget> totals;
  std::map<std::string, std::vector<std::pair<std::uint32_t, std::string>>> parts;
  for (const Model &model : models) {
    std::ifstream file(model.counts);
    std::string platform;
    std::uint32_t polygons = 0, vertices = 0;
    while (file >> platform >> polygons >> vertices) {
      totals[platform].polygons += polygons * model.howMany;
      totals[platform].vertices += vertices * model.howMany;
      const std::string modelName = model.counts.substr(model.counts.find_last_of('/') + 1);
      parts[platform].push_back(
          {polygons * model.howMany,
           modelName.substr(0, modelName.find('.')) + " x" + std::to_string(model.howMany)});
    }
  }
  std::ostringstream report;
  bool failed = false;
  for (const auto &[platform, limit] : limits) {
    const Cook::Budget &total = totals[platform];
    const bool over = !Cook::fits(total, limit);
    failed = failed || over;
    report << displayName(platform) << ": " << total.polygons << " of " << limit.polygons
           << " polygons, " << total.vertices << " of ";
    if (limit.vertices)
      report << limit.vertices;
    else
      report << "any number of";
    report << " vertices" << (over ? " (OVER)" : "") << "\n";
    auto &byCost = parts[platform];
    std::ranges::sort(byCost, std::greater<>());
    for (const auto &[polygons, model] : byCost)
      report << "  " << model << ": " << polygons << " polygons\n";
    if (over)
      std::fprintf(stderr,
                   "%s: shows more than %s draws a frame: %u polygons and %u vertices, against "
                   "%u and %u. The costliest:\n%s",
                   label.c_str(), displayName(platform).c_str(), total.polygons, total.vertices,
                   limit.polygons, limit.vertices, report.str().c_str());
  }
  if (!reportPath.empty())
    std::ofstream(reportPath) << report.str();
  return failed ? 1 : 0;
}

} // namespace

int main(int argc, char **argv) {
  const std::string command = argc > 1 ? argv[1] : "";
  if (command == "model")
    return cookModel(argc, argv);
  if (command == "scene")
    return checkScene(argc, argv);
  return usage("the command is model or scene");
}
